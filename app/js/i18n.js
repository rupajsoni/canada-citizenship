  function t(key, vars) {
    const dict = STRINGS[LANG] || STRINGS.en;
    let str = dict[key] ?? STRINGS.en[key] ?? key;
    if (vars) {
      Object.keys(vars).forEach(k => {
        str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return str;
  }

  function applyStaticI18n() {
    document.documentElement.setAttribute('lang', LANG);
    const switcher = document.getElementById('lang-switcher');
    if (switcher) switcher.value = LANG;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      // format: data-i18n-attr="title:support.cornerLabel,aria-label:support.cornerLabel"
      el.getAttribute('data-i18n-attr').split(',').forEach(pair => {
        const [attr, key] = pair.split(':').map(s => s.trim());
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });
  }

  function setLang(lang) {
    if (!SUPPORTED.includes(lang) || lang === LANG) return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch {}
    const url = new URL(location.href);
    url.searchParams.set('lang', lang);
    location.href = url.toString();
  }

  window.I18N = { t, lang: () => LANG, setLang, applyStaticI18n, SUPPORTED };
  document.addEventListener('DOMContentLoaded', applyStaticI18n);
